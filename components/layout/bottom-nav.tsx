interface BottomNavProps {
  role?: UserRole;
  userId?: string | null;
  initialUnreadCount?: number;
}

export default function BottomNav({
  role = "candidate",
  userId = null,
  initialUnreadCount = 0,
}: BottomNavProps) {
  const pathname = usePathname();
  const isMeetingRoom = typeof pathname === "string" && pathname.includes("/interviews/") && pathname.includes("/room");
  const [unreadCount, setUnreadCount] = useState(initialUnreadCount);

  const isApplicantRoute = pathname.startsWith("/applicant");
  const isEmployeeRoute = pathname.startsWith("/employee");

  const navItems = isApplicantRoute
    ? applicantNav
    : isEmployeeRoute
      ? employeeNav
      : role === "hr_manager" || role === "admin"
      ? hrNav
      : applicantNav;

  useEffect(() => {
    if (role !== "candidate" || !userId) {
      setUnreadCount(0);
      return;
    }

    const supabase = createClient();
    let isMounted = true;

    const refreshUnreadCount = async () => {
      const { count, error } = await supabase
        .from("notifications")
        .select("id", { count: "exact", head: true })
        .eq("recipient_id", userId)
        .eq("is_read", false);

      if (!isMounted || error) {
        return;
      }

      setUnreadCount(count ?? 0);
    };

    void refreshUnreadCount();

    const channel = supabase
      .channel(`notifications-${userId}-${Math.random().toString(36).slice(2,8)}`)
      .on(
        "postgres_changes",
        {
          event: "*",
          schema: "public",
          table: "notifications",
          filter: `recipient_id=eq.${userId}`,
        },
        () => {
          void refreshUnreadCount();
        }
      )
      .subscribe();

    return () => {
      isMounted = false;
      void supabase.removeChannel(channel);
    };
  }, [role, userId]);

  if (isMeetingRoom) return null;

  return (
    <nav className="md:hidden fixed bottom-0 left-0 w-full z-50 shadow-lg border-t border-border bg-surface flex justify-around items-center px-4 py-3 rounded-t-xl">
      {navItems.map((item) => {
        const isActive =
          pathname === item.href ||
          (item.href !== "/dashboard" && pathname.startsWith(item.href));
        return (
          <Link
            key={item.href}
            href={item.href}
            className={`flex flex-col items-center justify-center gap-1 text-center transition-all ${
              isActive
                ? "text-primary"
                : "text-on-surface-variant hover:bg-surface-container-high"
            }`}
          >
            <span className="relative flex items-center justify-center">
              {item.icon}
              {item.showBadge && unreadCount > 0 && (
                <span className="absolute -right-2 -top-1 min-w-5 rounded-full border border-border bg-error px-1.5 py-0.5 text-[10px] font-semibold leading-none text-white">
                  {unreadCount > 99 ? "99+" : unreadCount}
                </span>
              )}
            </span>
            <span className="text-[10px] font-label-caps">{item.label}</span>
          </Link>
        );
      })}
    </nav>
  );
}